#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate USER/Language.c from the translation CSV.

Usage:
    python gen_language.py <strings-translation-draft.csv> <Language.h> <output Language.c>

CSV columns (UTF-8, first row = header):
    String ID, Where it is shown, Max characters, English, Norwegian, Swedish, Danish, Finnish, German, (checks...)
Rows:
    STR_xxx      -> LanguageTable entry (must match StringID_t order in Language.h)
    WEEK_MON..SUN-> Week_Texts table
Rules:
    - Text must be ISO 8859-1 (Latin-1). Anything else is an error.
    - '|' marks a possible word break (soft hyphen 0xAD); only allowed in
      menu-row strings ("Menu row" in column 2).
    - Length is checked against "Max characters" (warning only).
    - Non-ASCII bytes are written as \\xNN; when the next character is a hex
      digit the literal is split ("Zur\\xFC" "cksetzen") so C does not
      swallow it into the escape.
"""
import csv
import re
import sys

LANGS = ['LANG_ENGLISH', 'LANG_Norwegian', 'LANG_Swedish', 'LANG_Danish', 'LANG_Finnish', 'LANG_German']
NATIVE = ['English', 'Norsk', 'Svenska', 'Dansk', 'Suomi', 'Deutsch']
WEEK = ['WEEK_MON', 'WEEK_TUE', 'WEEK_WED', 'WEEK_THU', 'WEEK_FRI', 'WEEK_SAT', 'WEEK_SUN']
TEXT_COL = 3  # English column index; next 5 columns are NO SV DA FI DE

HEADER = """//---------------------------------------------------------------------------------------------------------
//
// Copyright(c) 2026 E-Poly Technology Co., Ltd. All rights reserved.
//
//---------------------------------------------------------------------------------------------------------

//---------------------------------------------------------------------------------------------------------
// E-Poly North EU Thermostat Project
// Author: Benjamin Wang
// Date: 2026/06/03
// Email: Benjamin@epoly-tech.com
//---------------------------------------------------------------------------------------------------------

//---------------------------------------------------------------------------------------------------------
// File Function: Language string table definition
//      GENERATED by gen_language.py from strings-translation-draft.csv - edit the CSV, not this file.
//      Encoding: ISO 8859-1 bytes as \\xNN escapes. 0xAD = soft hyphen (menu-row word break).
//---------------------------------------------------------------------------------------------------------

#include "Language.h"

"""


def c_literal(s):
    """Return a C string literal (possibly split) for Latin-1 text s."""
    out = '"'
    i = 0
    while i < len(s):
        ch = s[i]
        o = ord(ch)
        if o > 255:
            raise ValueError('character %r (U+%04X) is not ISO 8859-1' % (ch, o))
        if ch == '"' or ch == '\\':
            out += '\\' + ch
        elif o < 32 or o > 126:
            out += '\\x%02X' % o
            if i + 1 < len(s) and s[i + 1] in '0123456789abcdefABCDEF':
                out += '" "'
        else:
            out += ch
        i += 1
    return out + '"'


def string_ids(header_text):
    i = header_text.index('STR_Save = 0')
    body = header_text[i:header_text.index('} StringID_t')]
    body = re.sub(r'//[^\n]*', '', body)
    ids = [re.sub(r'\s*=.*', '', x.strip()) for x in body.split(',') if x.strip()]
    return [x for x in ids if x != 'STR_MAX']


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    csv_path, h_path, out_path = sys.argv[1:]
    rows = list(csv.reader(open(csv_path, encoding='utf-8-sig')))[1:]
    table = {r[0].strip(): r for r in rows if r and r[0].strip()}
    ids = string_ids(open(h_path, encoding='latin-1').read())
    errors, warnings = [], []

    def text(row, li):
        s = row[TEXT_COL + li]
        is_row = row[1].startswith('Menu row')
        if '|' in s and not is_row:
            errors.append('%s %s: "|" only allowed in menu-row strings' % (row[0], LANGS[li]))
        if s == '':
            warnings.append('%s %s: empty, using English' % (row[0], LANGS[li]))
            s = row[TEXT_COL]
        try:
            mx = int(row[2].split('x')[-1])
            if len(s.replace('|', '')) > mx and not is_row:
                warnings.append('%s %s: "%s" %d chars > %d' % (row[0], LANGS[li], s, len(s), mx))
        except ValueError:
            pass
        return s.replace('|', '\xad')

    out = [HEADER, 'const char* const LanguageTable[STR_MAX][LANG_MAX] = {\n']
    for sid in ids:
        if sid not in table:
            errors.append('%s: missing in CSV' % sid)
            continue
        r = table[sid]
        out.append('\t// [%s]\n\t{\n' % sid)
        for li, lang in enumerate(LANGS):
            try:
                out.append('\t\t[%s] = %s,\n' % (lang, c_literal(text(r, li))))
            except ValueError as e:
                errors.append('%s %s: %s' % (sid, lang, e))
        out.append('\t},\n')
    out.append('};\n\n')

    out.append('// Weekday abbreviations (index 0 = Monday ... 6 = Sunday), 12x24 font on home screen\n')
    out.append('const char* const Week_Texts[LANG_MAX][7] = {\n')
    for li, lang in enumerate(LANGS):
        items = []
        for w in WEEK:
            if w not in table:
                errors.append('%s: missing in CSV' % w)
                continue
            items.append(c_literal(text(table[w], li)))
        out.append('\t[%s] = {%s},\n' % (lang, ', '.join(items)))
    out.append('};\n\n')

    out.append('// Language names in their own language (Language page, not translated)\n')
    out.append('const char* const Language_Native_Name[LANG_MAX] = {\n')
    for lang, n in zip(LANGS, NATIVE):
        out.append('\t[%s] = %s,\n' % (lang, c_literal(n)))
    out.append('};\n')

    for w in warnings:
        print('WARNING:', w)
    if errors:
        for e in errors:
            print('ERROR:', e)
        sys.exit(2)
    data = ''.join(out).replace('\r\n', '\n').replace('\n', '\r\n')
    open(out_path, 'w', encoding='latin-1', newline='').write(data)
    print('OK: %d strings x %d languages -> %s' % (len(ids), len(LANGS), out_path))


if __name__ == '__main__':
    main()
